const GLYPH_W = 5, GLYPH_H = 7, SPACING = 1;

/** Pixel width a string will occupy at the given integer scale. */
function textWidth(text, scale) {
  const n = String(text).length;
  return n > 0 ? (n * (GLYPH_W + SPACING) - SPACING) * scale : 0;
}

/**
 * A small RGB canvas with a few primitives — just what a thumbnail needs.
 */
class Canvas {
  constructor(width, height) {
    this.width = width;
    this.height = height;
    this.data = new Uint8Array(width * height * 3);
  }
  set(x, y, [r, g, b]) {
    if (x < 0 || y < 0 || x >= this.width || y >= this.height) return;
    const i = (y * this.width + x) * 3;
    this.data[i] = r; this.data[i + 1] = g; this.data[i + 2] = b;
  }
  /** Vertical gradient top→bottom between two colours. */
  fillGradient(top, bottom) {
    for (let y = 0; y < this.height; y++) {
      const t = y / (this.height - 1 || 1);
      const c = [
        Math.round(top[0] + (bottom[0] - top[0]) * t),
        Math.round(top[1] + (bottom[1] - top[1]) * t),
        Math.round(top[2] + (bottom[2] - top[2]) * t),
      ];
      for (let x = 0; x < this.width; x++) this.set(x, y, c);
    }
  }
  fillRect(x, y, w, h, color) {
    for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) this.set(xx, yy, color);
  }
  /** Draw text using the bitmap font at an integer scale. */
  drawText(text, x, y, scale, color) {
    let cx = x;
    for (const rawCh of String(text).toUpperCase()) {
      const glyph = FONT[rawCh] || FONT['?'];
      for (let row = 0; row < GLYPH_H; row++) {
        const bits = glyph[row];
        for (let col = 0; col < GLYPH_W; col++) {
          if (bits & (1 << (GLYPH_W - 1 - col))) {
            this.fillRect(cx + col * scale, y + row * scale, scale, scale, color);
          }
        }
      }
      cx += (GLYPH_W + SPACING) * scale;
    }
  }
  toPng() { return encodePng(this); }
}

module.exports = { encodePng, Canvas, textWidth, FONT };
